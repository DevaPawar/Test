public class UnaryOperators {
    public static void main(String[] args) {
        int a = 10, b = 5;
        a++;   // a is now 11
        b--;   // b is now 4
        a--;   // a is now 10 again
        b++;   // b is now 5 again
        System.out.println("a = " + a);   // 10
        System.out.println("b = " + b);   // 5
    }
}